void ui_draw_cat_avatar(int x, int y, bool user_variant) {
    ui_color_t frame =
        user_variant ? UI_COLOR_PRIMARY_DARK : UI_COLOR_PANEL_ALT;
    for (int row = 0; row < CAT_AVATAR_SIZE; ++row) {
        for (int column = 0; column < CAT_AVATAR_SIZE; ++column) {
            size_t pixel = (size_t)row * CAT_AVATAR_SIZE + column;
            uint8_t packed = s_cat_avatar_bitmap[pixel >> 1];
            uint8_t token =
                (pixel & 1) ? (packed & 0x0F) : (packed >> 4);
            ui_set_pixel(x + column, y + row,
                         token == CAT_FRAME_TOKEN
                             ? frame
                             : (ui_color_t)token);
        }
    }
}
